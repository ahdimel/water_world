"""Put every dollar in the same year.

Phase 2 left a known defect: Sorek's capex is 2013 dollars, Carlsbad's 2015, the
WateReuse O&M table 2011, energy prices 2025, and the Carlsbad prices quoted against one
another were from different years again. Comparing them directly is comparing different
units. This module restates everything in **2025 dollars** (`BASE_YEAR`).

The deflator is CPI-U all items (`CUUR0000SA0`), annual average. A construction cost
index (ENR CCI) would suit capex better, but it is paywalled, and the project's rule is
that every number traces to a source anyone can re-pull. CPI-U understates construction
inflation since 2020, so restating old capex with it is, if anything, generous to old
projects; that direction is noted wherever it matters.

The index table is COMMITTED (`data/parameters/cpi_u_annual.yaml`), generated from the
BLS cache by `rebuild()`, so the engine and the tests stay offline and deterministic.
A test re-derives the table from the cache whenever the cache is present.
"""

from __future__ import annotations

from collections import defaultdict
from datetime import date
from functools import lru_cache
from pathlib import Path

import yaml

from ww import params

BASE_YEAR = 2025

CPI_PATH = Path(__file__).resolve().parents[2] / "data" / "parameters" / "cpi_u_annual.yaml"

_SERIES = "bls.cpi.CUUR0000SA0"


def annual_from_cache() -> tuple[dict[int, float], dict[int, list[int]]]:
    """CPI-U annual averages from the cached BLS series, plus any months missing.

    BLS publishes an M13 annual average, but the parser drops it (mixing it into a
    monthly series corrupts the shape), so the average is recomputed here from the
    monthly values.

    A year with ONE month missing is kept and the gap recorded: BLS never published
    October 2025 because of the federal shutdown, and dropping 2025 would cost the base
    year. The latest year, if it has at least six months, is kept as a PROVISIONAL
    year-to-date average (2026 rate schedules need it) and listed as such. Any other
    gappy year is dropped.
    """
    from ww import cache, sources

    by_year: dict[int, dict[int, float]] = defaultdict(dict)
    for sid in ("bls.cpi.1990s", "bls.cpi.2000s", "bls.cpi.2010s", "bls.cpi.2020s"):
        src = sources.get(sid)
        for ts in src.normalise(cache.load(src.spec)):
            if ts.source_id != _SERIES:
                continue
            for p in ts.points:
                by_year[p.when.year][p.when.month] = p.value
    table: dict[int, float] = {}
    gaps: dict[int, list[int]] = {}
    latest = max(by_year)
    for y, months in sorted(by_year.items()):
        if len(months) < 11 and not (y == latest and len(months) >= 6):
            continue
        table[y] = round(sum(months.values()) / len(months), 3)
        if len(months) < 12:
            gaps[y] = [m for m in range(1, 13) if m not in months]
    return table, gaps


def rebuild(path: Path = CPI_PATH) -> Path:
    """Regenerate the committed index table from the cache."""
    table, gaps = annual_from_cache()
    doc = {
        "series": "CUUR0000SA0",
        "label": "CPI-U, all items, US city average, annual average of monthly values",
        "citation": "bls_cpi",
        "generated": date.today().isoformat(),
        "missing_months": gaps,
        "provisional": [y for y in table if y > BASE_YEAR],
        "annual": table,
    }
    header = "# GENERATED by `python -m ww deflator --rebuild` from the BLS cache. Do not edit.\n"
    path.write_text(header + yaml.safe_dump(doc, sort_keys=False))
    load.cache_clear()
    return path


@lru_cache(maxsize=1)
def load() -> dict[int, float]:
    doc = yaml.safe_load(CPI_PATH.read_text())
    return {int(k): float(v) for k, v in doc["annual"].items()}


def factor(from_year: float, to_year: int = BASE_YEAR) -> float:
    """Multiply a `from_year` dollar amount by this to express it in `to_year` dollars.

    A fractional year (2016.5) interpolates linearly between annual averages, which is
    how a fiscal-year figure straddling two calendar years is handled.
    """
    table = load()
    return _index(to_year, table) / _index(from_year, table)


def _index(year: float, table: dict[int, float]) -> float:
    lo = int(year)
    if lo not in table:
        raise KeyError(f"no CPI-U annual average for {lo}; table covers {min(table)}-{max(table)}")
    frac = year - lo
    if frac == 0:
        return table[lo]
    if lo + 1 not in table:
        raise KeyError(f"no CPI-U annual average for {lo + 1}")
    return table[lo] * (1 - frac) + table[lo + 1] * frac


def to_base(amount: float, year: float) -> float:
    """Restate a nominal amount from `year` dollars in BASE_YEAR dollars."""
    return amount * factor(year)


def real(pid: str) -> float:
    """A dollar parameter's value in BASE_YEAR dollars.

    Raises if the parameter has no `year`: silently treating an undated dollar figure as
    current is exactly the error this module exists to remove.
    """
    p = params.get(pid)
    if p.year is None:
        raise ValueError(f"{pid!r} has no dollar year; set `year:` in literature.yaml")
    return to_base(p.value, p.year)


def real_band(pid: str) -> tuple[float, float]:
    p = params.get(pid)
    if p.year is None:
        raise ValueError(f"{pid!r} has no dollar year; set `year:` in literature.yaml")
    lo, hi = params.band(pid)
    return to_base(lo, p.year), to_base(hi, p.year)
